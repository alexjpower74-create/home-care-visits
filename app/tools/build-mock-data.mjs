// Writes app/public/mock-data.js (for ?mock=1 only) from data/sample-agency.json. Run: node app/tools/build-mock-data.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = JSON.parse(fs.readFileSync(path.join(here, '../../data/sample-agency.json'), 'utf8'));
const LABEL = {
  personal_care: 'Personal care', meal_prep: 'Meal preparation', medication_reminder: 'Medication reminder',
  housekeeping: 'Light housekeeping', laundry: 'Laundry', companionship: 'Companionship',
  errands: 'Errands and shopping', other: 'Other',
};
const out = {
  agency: { name: src.agency.name, office_phone: src.agency.office_phone, timezone: src.agency.timezone },
  workers: src.workers.map(w => ({ id: w.ref, name: w.name, phone: w.phone, key: `mock-w${w.ref}` })),
  clients: src.clients.map(c => ({
    id: c.ref, name: c.name, address: c.address, lat: c.lat, lng: c.lng, entry_notes: c.entry_notes,
    tasks: c.tasks.map((t, i) => ({ id: c.ref * 10 + i + 1, kind: t.kind, label: LABEL[t.kind], detail: t.detail || '' })),
    patterns: c.patterns.map((p, i) => ({ id: c.ref * 10 + i + 1, days: p.days, start: p.start, end: p.end, worker_id: p.worker })),
    family_key: `mock-f${c.ref}`,
  })),
};
const file = path.join(here, '../public/mock-data.js');
fs.writeFileSync(file, `// Generated by app/tools/build-mock-data.mjs from data/sample-agency.json. SAMPLE people, for ?mock=1 only.\nexport default ${JSON.stringify(out, null, 1)};\n`);
console.log('wrote', path.relative(process.cwd(), file));
