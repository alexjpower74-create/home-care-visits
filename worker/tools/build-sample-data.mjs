// Writes src/sample-data.js from ../data/sample-agency.json, so the Worker never reads outside worker/.
// Run after the data file changes: npm run build:sample. tests/unit.test.mjs fails when the output is stale.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

export function sampleData() {
  const d = JSON.parse(readFileSync(join(root, '..', 'data', 'sample-agency.json'), 'utf8'))
  return {
    agency: {
      name: d.agency.name,
      office_phone: d.agency.office_phone,
      timezone: d.agency.timezone,
      office: { label: d.agency.office.label, lat: d.agency.office.lat, lng: d.agency.office.lng },
      pin: d.agency.pin,
    },
    zones: d.zones.map((z) => ({ id: z.id, name: z.name })),
    funders: d.funders.map((f) => ({ id: f.id, name: f.name })),
    workers: d.workers.map((w) => ({
      ref: w.ref,
      name: w.name,
      phone: w.phone,
      zone_ids: w.zone_ids,
      availability: w.availability,
      max_week_minutes: w.max_week_minutes,
    })),
    clients: d.clients.map((c) => ({
      ref: c.ref,
      name: c.name,
      address: c.address,
      lat: c.lat,
      lng: c.lng,
      zone_id: c.zone_id,
      funder_id: c.funder_id,
      entry_notes: c.entry_notes,
      tasks: c.tasks.map((t) => ({ kind: t.kind, detail: t.detail })),
      patterns: c.patterns.map((p) => ({ days: p.days, start: p.start, end: p.end, worker: p.worker })),
      family_contacts: c.family_contacts.map((f) => ({ name: f.name, relationship: f.relationship, phone: f.phone })),
    })),
    expected_base_week_conflicts: d.expected_base_week_conflicts,
  }
}

export const render = (data) => `// GENERATED by tools/build-sample-data.mjs from data/sample-agency.json. Do not edit by hand.
// SAMPLE data: made-up people labelled SAMPLE, pins at stated offsets from real community points, no street addresses.
// \`worker\` on a pattern is the 1-based index into \`workers\` (null = unassigned).
export const SAMPLE = ${JSON.stringify(data, null, 2)}
`

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(root, 'src', 'sample-data.js'), render(sampleData()))
  console.log('wrote src/sample-data.js')
}
